#!/usr/bin/env python3
"""Regenerate crews/members.json from the desk's sectors.yaml and roles.yaml.

members.json is a build product. The six standing roles are fixed; everything
below them is generated by crossing two config files -- sectors.yaml says how many
pods there are and what each covers, roles.yaml says what a pod is made of. Every
pod gets a line manager plus one row per role. Generating them removes the only
real drift risk: near-identical hand-typed entries whose ticker lists go stale the
moment a ticker moves pods.

Nothing about the team composition lives in this file. Cut the debate roles, add a
macro hedger, drop the analysts from four to two -- edit roles.yaml and re-run.

Both files are looked up in $DESK_ROOT first (that tree is your data), and fall
back to this repository's config/*.example.yaml so a fresh clone runs.

An IC is spawned per ticker per round and has no standing session, so its row
carries no ``slot_hint``; ``artifact_globs`` and ``per_ticker`` say which files
it writes, and the backend folds its state from those. That table mirrors the
stage table in ``scripts/desk_events.py``.

Duty copy is an outward-facing job description: what this member does for the
reader. Never put orchestration internals in it (sentinel strings, tool or command
names, session mechanics) -- that is prompt material, not UI copy.

Usage:
    python3 crews/gen_members.py            # write crews/members.json
    python3 crews/gen_members.py --check    # exit 1 if the committed file is stale
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import yaml

APP_ROOT = Path(__file__).resolve().parent.parent
DESK_ROOT = Path(os.environ.get("DESK_ROOT") or Path.home() / "trading-desk")
OUT_PATH = Path(__file__).resolve().parent / "members.json"

#: Config lookup: the desk root wins, the shipped example is the fallback. Two
#: entries rather than one so a clone with no desk root still generates a roster
#: -- which is what lets the test suite run before anyone has a desk.
CONFIG_SOURCES = {
    "sectors": (DESK_ROOT / "sectors.yaml", APP_ROOT / "config" / "sectors.example.yaml"),
    "roles": (DESK_ROOT / "roles.yaml", APP_ROOT / "config" / "roles.example.yaml"),
    "books": (DESK_ROOT / "books.yaml", APP_ROOT / "config" / "books.example.yaml"),
}

