# --- the IC layer -----------------------------------------------------------
#
# Read from roles.yaml, not written here. That file is the entry point for
# composing a team: the roles it lists are the rows every pod gets, in the order
# it lists them.
#
# Each role is spawned per ticker per round rather than kept as a standing
# session, so an IC row carries no ``slot_hint``: its state is folded from the
# artifacts it writes. ``artifacts`` and ``per_ticker`` mirror the stage table in
# ``scripts/desk_events.py``; ``per_ticker: ~`` means "scale with the pod's
# analyst_copies".
#
# ``title`` is required to be ENGLISH, like the six standing roles' -- the display
# language is mapped in ``ui/i18n.mjs`` (``memberTitle``), which is what makes the
# app's language switch reach these rows. A title stored here in another language
# survives the switch and prints the wrong language to the other half of the
# readers.


class ConfigProblem(Exception):
    """A config file is missing or malformed. Reported, never guessed around."""


def _config_path(kind: str) -> Path:
    """The file to read for ``kind``: the desk root's, else the shipped example."""
    primary, fallback = CONFIG_SOURCES[kind]
    if primary.is_file():
        return primary
    if fallback.is_file():
        return fallback
    raise ConfigProblem(
        f"no {kind} config: looked for {primary} then {fallback}"
    )


def _load_mapping(kind: str) -> dict:
    path = _config_path(kind)
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise ConfigProblem(f"{path}: not valid YAML -- {exc}") from exc
    if not isinstance(data, dict):
        raise ConfigProblem(f"{path}: top level must be a mapping")
    return data


#: Every field a role must supply. Validated on load rather than at render time,
#: so a typo names the file and the row instead of raising a KeyError deep inside
#: the builder.
_ROLE_FIELDS = ("role", "title", "letter", "agent", "duty", "artifacts")


def load_roles() -> tuple[dict, ...]:
    """The IC roles, in file order, validated."""
    path = _config_path("roles")
    raw = _load_mapping("roles").get("roles")
    if not isinstance(raw, list) or not raw:
        raise ConfigProblem(f"{path}: needs a non-empty 'roles' list")
    roles: list[dict] = []
    seen: set[str] = set()
    for index, entry in enumerate(raw):
        at = f"{path}: roles[{index}]"
        if not isinstance(entry, dict):
            raise ConfigProblem(f"{at} must be a mapping")
        missing = [f for f in _ROLE_FIELDS if not entry.get(f)]
        if missing:
            raise ConfigProblem(f"{at} is missing {', '.join(missing)}")
        role = str(entry["role"])
        if not role.replace("-", "").isalnum() or not role.islower():
            raise ConfigProblem(
                f"{at}: role {role!r} must be lowercase letters, digits and dashes "
                "-- it becomes part of the member id"
            )
        if role in seen:
            raise ConfigProblem(f"{at}: duplicate role {role!r}")
        seen.add(role)
        artifacts = entry["artifacts"]
        if not isinstance(artifacts, list) or not all(artifacts):
            raise ConfigProblem(f"{at}: artifacts must be a non-empty list of globs")
        per_ticker = entry.get("per_ticker")
        if per_ticker is not None and not (isinstance(per_ticker, int) and per_ticker > 0):
            raise ConfigProblem(
                f"{at}: per_ticker must be a positive integer or null "
                "(null = scale with the pod's analyst_copies)"
            )
        roles.append({
            "role": role,
            "title": str(entry["title"]),
            "letter": str(entry["letter"]),
            "agent": str(entry["agent"]),
            "duty": " ".join(str(entry["duty"]).split()),
            "globs": [str(g) for g in artifacts],
            "per_ticker": per_ticker,
        })
    return tuple(roles)


def load_book_labels() -> dict[str, str]:
    """``{book id: display label}`` from books.yaml, empty when there is none.

    Optional on purpose: a desk with no books.yaml still generates a roster, its
    pod rows just fall back to the book id.
    """
    try:
        raw = _load_mapping("books").get("books")
    except ConfigProblem:
        return {}
    if not isinstance(raw, dict):
        return {}
    out: dict[str, str] = {}
    for key, cfg in raw.items():
        label = (cfg or {}).get("label") if isinstance(cfg, dict) else None
        out[str(key)] = str(label) if label else str(key)
    return out


def load_pods() -> list[tuple[str, list[str], str]]:
    """Pods in sectors.yaml order: ``(pod, tickers, book)``.

    ``book`` names the entry in books.yaml this pod trades against. It is carried
    here because the org chart labels a pod row with it, and a label composed from
    a fixed string would claim every pod trades the same book.
    """
    pods = _load_mapping("sectors").get("sectors") or {}
    out: list[tuple[str, list[str], str]] = []
    for pod, cfg in pods.items():
        cfg = cfg or {}
        out.append((
            str(pod),
            [str(t) for t in (cfg.get("tickers") or [])],
            str(cfg.get("book") or ""),
        ))
    return out


