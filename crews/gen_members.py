def render(doc: dict) -> str:
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if members.json differs from generator output",
    )
    ap.add_argument(
        "--out",
        type=Path,
        default=OUT_PATH,
        help="write the roster to this path (default: crews/members.json). Point it at a "
        "temp path with DESK_ROOT set to generate a roster for another desk without "
        "touching the committed file. Ignored by --check, which always compares the "
        "committed crews/members.json.",
    )
    args = ap.parse_args()

    try:
        doc = build(load_pods(), load_roles())
    except ConfigProblem as exc:
        print(f"config error: {exc}", file=sys.stderr)
        return 2
    text = render(doc)
    if args.check:
        current = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.exists() else ""
        if current != text:
            print(f"STALE: {OUT_PATH} differs from generator output", file=sys.stderr)
            return 1
        print(f"OK: {OUT_PATH} matches {_config_path('sectors')} + {_config_path('roles')}")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(json.loads(text)['members'])} members)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
